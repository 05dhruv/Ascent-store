const BASE_CLASS = "app-icon";

/**
 * Accepts the legacy Tabler names ("ti-home", "home", or "ti ti-home text-sm")
 * so icon names kept in config objects keep working unchanged.
 */
export default function Icon({ name, className = "", ...props }) {
  const tokens = String(name || "").trim().split(/\s+/).filter((token) => token !== "ti");
  const iconToken = tokens.find((token) => token.startsWith("ti-")) || tokens[0] || "";
  const extraClasses = tokens.filter((token) => token !== iconToken).join(" ");
  const Component = ICONS[iconToken.replace(/^ti-/, "")] || Circle;
  return (
    <Component
      aria-hidden="true"
      width="1em"
      height="1em"
      {...props}
      className={[BASE_CLASS, extraClasses, className].filter(Boolean).join(" ")}
    />
  );
}
